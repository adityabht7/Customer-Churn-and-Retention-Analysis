"""
Report generation utilities: Prioritized Outreach CSV and Executive Retention Brief.
"""

from typing import Dict, Any, List
import io
import pandas as pd
from reportlab.lib.pagesizes import letter
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib import colors

def generate_prioritized_outreach_list(scored_df: pd.DataFrame, top_n: int = 500) -> pd.DataFrame:
    """
    Filters and sorts customers by highest churn risk and highest revenue exposure,
    producing an actionable call list for Customer Success / Account Management.
    """
    cols = [
        "customerID", "Churn_Probability", "Risk_Tier", "MonthlyCharges",
        "tenure", "Contract", "SupportTickets", "SatisfactionScore", "PaymentMethod"
    ]
    available_cols = [c for c in cols if c in scored_df.columns]
    
    # Sort descending by Churn_Probability and MonthlyCharges
    sorted_df = scored_df.sort_values(
        by=["Churn_Probability", "MonthlyCharges"],
        ascending=[False, False]
    )[available_cols].copy()

    # Add recommended action preview
    actions = []
    for _, row in sorted_df.iterrows():
        contract = row.get("Contract", "")
        tickets = row.get("SupportTickets", 0)
        csat = row.get("SatisfactionScore", 3)
        if tickets >= 3 or csat <= 2:
            actions.append("VIP Concierge Tech Support Escalation")
        elif contract == "Month-to-month":
            actions.append("1-Year Contract Upgrade Offer (15% Off)")
        elif row.get("PaymentMethod") == "Electronic check":
            actions.append("Auto-Pay Enrollment $15 Credit")
        else:
            actions.append("Proactive Account Review & Loyalty Perk")
            
    sorted_df["Recommended_Action"] = actions
    return sorted_df.head(top_n)


def generate_executive_text_summary(kpis: Dict[str, Any], benchmark: Dict[str, Any], roi: Dict[str, Any]) -> str:
    """
    Generates a structured Executive Summary report in Markdown format.
    """
    md = f"""# Executive Customer Churn & Retention Intelligence Report

## 1. Executive Summary & Core Financials
- **Total Customer Base:** {kpis.get('total_customers', 0):,} accounts
- **Overall Churn Rate:** {kpis.get('churn_rate', 0.0):.2f}%
- **Total Monthly Recurring Revenue (MRR):** ${kpis.get('total_mrr', 0.0):,.2f}
- **MRR Directly at Risk:** ${kpis.get('mrr_at_risk', 0.0):,.2f} ({kpis.get('mrr_risk_pct', 0.0):.1f}% of total MRR)
- **Average Customer Lifetime Value (CLV):** ${kpis.get('avg_clv', 0.0):,.2f}
- **Average Account Tenure:** {kpis.get('avg_tenure', 0.0):.1f} months

---

## 2. Predictive Machine Learning Benchmark
- **Champion Classification Model:** {benchmark.get('best_model_name', 'Gradient Boosting')}
- **Model Discriminative Power (ROC-AUC):** {benchmark.get('best_roc_auc', 0.0):.4f}
- **Top Root Drivers of Customer Churn:**
"""
    for i, item in enumerate(benchmark.get("feature_importances", [])[:5], 1):
        md += f"  {i}. **{item['feature']}** (Predictive Weight: {item['importance']:.3f})\n"

    md += f"""
---

## 3. Targeted Retention Campaign Financial Model
- **Identified At-Risk Customer Cohort:** {roi.get('at_risk_count', 0):,} accounts
- **Total Campaign Budget:** ${roi.get('total_campaign_cost', 0.0):,.2f}
- **Target Projected Saves:** {roi.get('customers_saved', 0):,} accounts
- **Preserved Annual Recurring Revenue:** ${roi.get('annual_revenue_saved', 0.0):,.2f}
- **Net Bottom-Line Profit:** ${roi.get('net_profit', 0.0):,.2f}
- **Projected Campaign ROI:** **{roi.get('roi_pct', 0.0):.1f}%**

---
*Report generated by Customer Retention Analytics Engine.*
"""
    return md


def generate_pdf_summary_report(kpis: Dict[str, Any], benchmark: Dict[str, Any]) -> bytes:
    """
    Creates an executive PDF report using ReportLab.
    """
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=letter, rightMargin=36, leftMargin=36, topMargin=36, bottomMargin=36)
    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        "ReportTitle",
        parent=styles["Heading1"],
        fontSize=20,
        leading=24,
        textColor=colors.HexColor("#1E293B")
    )
    section_style = ParagraphStyle(
        "SectionHeading",
        parent=styles["Heading2"],
        fontSize=14,
        leading=18,
        textColor=colors.HexColor("#4F46E5"),
        spaceBefore=14,
        spaceAfter=6
    )
    body_style = ParagraphStyle(
        "BodyDark",
        parent=styles["Normal"],
        fontSize=10,
        leading=14,
        textColor=colors.HexColor("#334155")
    )

    story = []
    story.append(Paragraph("Customer Churn & Retention Intelligence Report", title_style))
    story.append(Spacer(1, 10))
    story.append(Paragraph("Executive Brief & Predictive Model Evaluation", body_style))
    story.append(Spacer(1, 15))

    story.append(Paragraph("1. Core Business & Portfolio Metrics", section_style))
    kpi_data = [
        ["Metric", "Value"],
        ["Total Customer Accounts", f"{kpis.get('total_customers', 0):,}"],
        ["Current Churn Rate", f"{kpis.get('churn_rate', 0.0):.2f}%"],
        ["Total Monthly Recurring Revenue (MRR)", f"${kpis.get('total_mrr', 0.0):,.2f}"],
        ["MRR at Risk (Churn Exposure)", f"${kpis.get('mrr_at_risk', 0.0):,.2f}"],
        ["Average Customer Lifetime Value (CLV)", f"${kpis.get('avg_clv', 0.0):,.2f}"],
        ["Average Customer Tenure", f"{kpis.get('avg_tenure', 0.0):.1f} months"],
    ]
    t1 = Table(kpi_data, colWidths=[240, 240])
    t1.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#4F46E5")),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.whitesmoke),
        ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
    ]))
    story.append(t1)
    story.append(Spacer(1, 15))

    story.append(Paragraph("2. Champion Machine Learning Model", section_style))
    model_data = [
        ["Model Property", "Details"],
        ["Champion Algorithm", benchmark.get('best_model_name', 'Gradient Boosting')],
        ["ROC-AUC Score", f"{benchmark.get('best_roc_auc', 0.0):.4f}"],
        ["Evaluated Samples", f"{benchmark.get('total_test_samples', 0):,}"],
    ]
    t2 = Table(model_data, colWidths=[240, 240])
    t2.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#10B981")),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.whitesmoke),
        ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
    ]))
    story.append(t2)

    doc.build(story)
    buffer.seek(0)
    return buffer.getvalue()
